#pragma once

#include <stdint.h>

/*
 * netrand.c — общий источник непредсказуемости для TCP ISN/локального
 * порта и DNS transaction id/источника UDP-порта (0.9.5) — раньше все
 * четыре были предсказуемы (линейный счётчик или счётчик тиков с
 * фиксированным умножением), что оставляло классические дыры: угадываемый
 * TCP ISN/порт облегчает off-path инъекцию сегментов в "соединение",
 * угадываемый DNS txid+порт — отравление кэша поддельным ответом (ни то,
 * ни другое не проверяется никак, кроме самого значения).
 *
 * Тот же приём, что уже в tls.c (tls_gather_random()) — rdtsc + счётчик
 * тиков PIT + монотонный счётчик, прокрученные через SHA-256-пул, чтобы
 * повторные вызовы не отдавали коррелированные байты. СВОЙ отдельный пул,
 * не общий с tls.c — модули остаются независимыми друг от друга. Та же
 * оговорка, что у tls_gather_random(): RNG в системе нет, RDRAND не
 * проверяется, в детерминированном эмуляторе rdtsc предсказуемее, чем на
 * реальном железе — это ЗАМЕТНО лучше счётчика/умножения тиков, но не
 * криптографическая случайность.
 */

uint32_t netrand_u32(void);
uint16_t netrand_u16(void);
