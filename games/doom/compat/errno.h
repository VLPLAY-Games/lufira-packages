// errno.h — минимальная замена для порта doomgeneric. m_misc.c проверяет
// только errno==EISDIR (как признак "open() упал, потому что path — это
// каталог, а не файл") — у нас compat.c никогда не выставляет errno в это
// значение (fopen() там просто возвращает NULL при любой ошибке), так что
// M_FileExists() трактует каталог как "файла нет" — не 1:1 с POSIX, но
// Doom нигде не передаёт туда путь к каталогу, так что разницы не видно.
#pragma once

extern int errno;

#define EISDIR 21
